#include <stddef.h>
#include <stdlib.h>
#include "libft.h"

t_list	*ft_lstnew(void *content)
{
	t_list	*node;

	node = malloc(sizeof(*node));
	if (!node)
		return (node);
	node->content = content;
	node->next = NULL;
	return (node);
}
